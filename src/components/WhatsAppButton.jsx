import { useState, useEffect } from 'react'

export default function WhatsAppButton() {
  const [isVisible, setIsVisible] = useState(false)

  useEffect(() => {
    const handleScroll = () => {
      setIsVisible(window.scrollY > 300)
    }
    window.addEventListener('scroll', handleScroll)
    return () => window.removeEventListener('scroll', handleScroll)
  }, [])

  const handleClick = () => {
    window.open('https://wa.me/51999999999', '_blank')
  }

  return (
    <button
      onClick={handleClick}
      className={`fixed bottom-6 right-6 z-50 flex items-center justify-center w-14 h-14 rounded-full bg-[#25D366] text-white shadow-lg hover:shadow-xl hover:scale-110 active:scale-95 transition-all duration-300 ${
        isVisible ? 'opacity-100 translate-y-0' : 'opacity-0 translate-y-4 pointer-events-none'
      }`}
      aria-label="Contactar por WhatsApp"
    >
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        className="w-7 h-7"
      >
        <path d="M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.149-.473-.224-.672.224-.197.336-.387.352-.575.107-.559-.15-1.036-.465-1.47-.784-.386-.783-.842-1.71-.21-2.625.315-.561.348-.932.357-1.322.012-.431-.168-.819-.277-1.195-.466-.473-.272-.604-.669-.33-1.016.337-.347.363-.8.258-1.194-.121-.431-.787-.822-1.457-.963-.671-.14-1.365-.055-2.016.396C4.82 5.68 3.04 8.295 2.718 8.84c-.272.473-.48.938-.48 1.36 0 2.97 2.405 5.833 3.098 6.567.554.607 5.928 4.405 6.467 4.97.54.566 1.102.045 1.502-.302.372-.284.673-.782.752-1.284.114-.707.177-1.485.168-2.18-.03-.788-.294-1.196-.641-1.358-.347-.161-.726-.242-1.105-.242-.378 0-.756.03-1.133.096-.377.066-.726.441-1.333.824-.607.383-.973.553-1.43.553-.457 0-.82-.388-.82-.863 0-.473.382-.906.941-1.273.56-.367 1.24-.566 1.807-.566.566 0 1.146.199 1.807.566.661.367 1.043.8.941 1.273-.082.475-.475.848-.82.863.345.015.824-.116 1.43-.553.607-.383.97-.757 1.333-.824.377-.066.756-.096 1.133-.096.379 0 .758.08 1.105.242.347.162.71.57.641 1.358.114.695-.088 1.088.484 1.502 1.284.4.4.93.849 1.105 1.194.302.345.43.748.258 1.194-.15.49-.49.823-.752 1.016-.347.182-.676.602-.641 1.358.03.695-.054 1.326-.168 1.805-.505.479-.457.849-.93 1.105-1.417.257-.488.22-.97.094-1.443-.126-.473-.441-.826-.853-1.053-.412-.226-.862-.292-1.312-.187-.45.105-.861.36-1.222.72-.361.36-.67.505-.909.145-.24.287-.433.414-.595z" />
      </svg>
    </button>
  )
}
